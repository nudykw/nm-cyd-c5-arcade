//! Рушій **3D Sokoban** з рівнями оригінальної гри (Thinking Rabbit, 1982 / набір XSokoban).
//!
//! Без `std`, без `alloc` — логіка перевіряється на хості.
//!
//! Логіка (класичний Sokoban):
//! - гравець ходить по 4 напрямках і штовхає по одному ящику;
//! - ящик не можна штовхнути в стіну, в інший ящик або за межі кімнати;
//! - рівень пройдено, коли ВСІ ящики стоять на цілях;
//! - `Undo` (кільцевий буфер на 1024 ходи), `Reset`, перехід по колу між рівнями;
//! - «порожнеча» поза стінами обчислюється заливкою від гравця, тому мапи з пробілами
//!   навколо кімнати (як в оригінальних рівнях) розбираються правильно.
//!
//! Рівні — класичні 50 рівнів оригінального Sokoban у форматі XSB
//! (джерело: набір XSokoban, `xsokoban0001..0050.sok`).

