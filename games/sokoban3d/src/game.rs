#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Dir {
    Up = 0,
    Right = 1,
    Down = 2,
    Left = 3,
}

impl Dir {
    #[inline]
    pub const fn delta(self) -> (i32, i32) {
        match self {
            Self::Up => (0, -1),
            Self::Right => (1, 0),
            Self::Down => (0, 1),
            Self::Left => (-1, 0),
        }
    }

    #[inline]
    pub const fn from_u8(v: u8) -> Self {
        match v & 3 {
            0 => Self::Up,
            1 => Self::Right,
            2 => Self::Down,
            _ => Self::Left,
        }
    }
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum MoveResult {
    Moved,
    Pushed,
    Blocked,
    Solved,
}

#[derive(Clone)]
pub struct Sokoban {
    pub w: usize,
    pub h: usize,
    pub wall: [bool; MAX_CELLS],
    pub inside: [bool; MAX_CELLS],
    pub goal: [bool; MAX_CELLS],
    pub box_at: [bool; MAX_CELLS],
    pub player: usize,
    pub moves: u32,
    pub pushes: u32,
    pub level: usize,
    undo: [u8; 1024],
    undo_head: usize,
    undo_len: usize,
    pub cleared: bool,
}

impl Sokoban {
    /// Розбір мапи у форматі XSB. `level` — номер для UI/статистики.
    pub fn parse(rows: &[&str], level: usize) -> Self {
        let h = rows.len().min(MAX_H);
        let mut w = 0usize;
        for r in rows.iter().take(h) {
            w = w.max(r.len());
        }
        let w = w.min(MAX_W);

        let mut s = Self {
            w,
            h,
            wall: [false; MAX_CELLS],
            inside: [false; MAX_CELLS],
            goal: [false; MAX_CELLS],
            box_at: [false; MAX_CELLS],
            player: 0,
            moves: 0,
            pushes: 0,
            level,
            undo: [0; 1024],
            undo_head: 0,
            undo_len: 0,
            cleared: false,
        };

        for (y, row) in rows.iter().take(h).enumerate() {
            for (x, ch) in row.bytes().enumerate().take(w) {
                let i = y * MAX_W + x;
                match ch {
                    b'#' => s.wall[i] = true,
                    b'.' => s.goal[i] = true,
                    b'$' => s.box_at[i] = true,
                    b'*' => {
                        s.goal[i] = true;
                        s.box_at[i] = true;
                    }
                    b'@' | b'+' => {
                        if ch == b'+' {
                            s.goal[i] = true;
                        }
                        s.player = i;
                    }
                    _ => {}
                }
            }
        }

        // Кімната = усе, що досяжне від гравця по не-стінах (ящики вважаємо прохідними).
        // Пробіли поза стінами оригінальних рівнів таким чином стають «порожнечею».
        let mut inside = [false; MAX_CELLS];
        let mut queue = [0u16; MAX_CELLS];
        let mut head = 0usize;
        let mut tail = 0usize;
        if s.player < MAX_CELLS {
            inside[s.player] = true;
            queue[tail] = s.player as u16;
            tail += 1;
        }
        while head < tail {
            let cur = queue[head] as usize;
            head += 1;
            let (cx, cy) = ((cur % MAX_W) as i32, (cur / MAX_W) as i32);
            for (dx, dy) in [(-1i32, 0i32), (1, 0), (0, -1), (0, 1)] {
                let nx = cx + dx;
                let ny = cy + dy;
                if nx < 0 || ny < 0 || nx >= w as i32 || ny >= h as i32 {
                    continue;
                }
                let ni = (ny as usize) * MAX_W + nx as usize;
                if inside[ni] || s.wall[ni] {
                    continue;
                }
                inside[ni] = true;
                if tail < MAX_CELLS {
                    queue[tail] = ni as u16;
                    tail += 1;
                }
            }
        }
        s.inside = inside;
        s
    }

    pub fn load(level: usize) -> Self {
        let idx = level % LEVELS.len();
        Self::parse(LEVELS[idx], idx)
    }

    #[inline]
    pub fn idx(&self, x: i32, y: i32) -> Option<usize> {
        if x < 0 || y < 0 || x >= self.w as i32 || y >= self.h as i32 {
            return None;
        }
        Some((y as usize) * MAX_W + x as usize)
    }

    #[inline]
    pub fn cell(&self, i: usize) -> Option<(i32, i32)> {
        if i >= MAX_CELLS {
            return None;
        }
        Some(((i % MAX_W) as i32, (i / MAX_W) as i32))
    }

    pub fn box_count(&self) -> usize {
        self.box_at.iter().filter(|&&b| b).count()
    }

    pub fn goal_count(&self) -> usize {
        self.goal.iter().filter(|&&g| g).count()
    }

    pub fn boxes_on_goals(&self) -> usize {
        (0..MAX_CELLS).filter(|&i| self.box_at[i] && self.goal[i]).count()
    }

    pub fn is_solved(&self) -> bool {
        let n = self.box_count();
        n > 0 && self.boxes_on_goals() == n
    }

    pub fn try_move(&mut self, d: Dir) -> MoveResult {
        if self.cleared {
            return MoveResult::Blocked;
        }
        let Some((x, y)) = self.cell(self.player) else {
            return MoveResult::Blocked;
        };
        let (dx, dy) = d.delta();
        let Some(target) = self.idx(x + dx, y + dy) else {
            return MoveResult::Blocked;
        };
        if !self.inside[target] || self.wall[target] {
            return MoveResult::Blocked;
        }

        let mut pushed = false;
        if self.box_at[target] {
            let Some(beyond) = self.idx(x + 2 * dx, y + 2 * dy) else {
                return MoveResult::Blocked;
            };
            if !self.inside[beyond] || self.wall[beyond] || self.box_at[beyond] {
                return MoveResult::Blocked;
            }
            self.box_at[target] = false;
            self.box_at[beyond] = true;
            self.pushes += 1;
            pushed = true;
        }

        self.player = target;
        self.moves += 1;

        // Кільцевий буфер історії: працює навіть на рівнях, де ходів тисячі
        self.undo[self.undo_head] = d as u8;
        self.undo_head = (self.undo_head + 1) % self.undo.len();
        if self.undo_len < self.undo.len() {
            self.undo_len += 1;
        }

        if self.is_solved() {
            self.cleared = true;
            return MoveResult::Solved;
        }
        if pushed {
            MoveResult::Pushed
        } else {
            MoveResult::Moved
        }
    }

    pub fn can_undo(&self) -> bool {
        self.undo_len > 0
    }

    pub fn undo(&mut self) -> bool {
        if self.undo_len == 0 {
            return false;
        }
        self.undo_head = (self.undo_head + self.undo.len() - 1) % self.undo.len();
        self.undo_len -= 1;
        let d = Dir::from_u8(self.undo[self.undo_head]);
        let Some((x, y)) = self.cell(self.player) else {
            return false;
        };
        let (dx, dy) = d.delta();
        let Some(prev) = self.idx(x - dx, y - dy) else {
            return false;
        };
        let Some(ahead) = self.idx(x + dx, y + dy) else {
            return false;
        };
        if self.box_at[ahead] {
            self.box_at[ahead] = false;
            self.box_at[self.player] = true;
            self.pushes = self.pushes.saturating_sub(1);
        }
        self.player = prev;
        self.moves = self.moves.saturating_sub(1);
        self.cleared = false;
        true
    }

    pub fn reset(&mut self) {
        let level = self.level;
        *self = Self::load(level);
    }

    pub fn next_level(&mut self) {
        let next = (self.level + 1) % LEVELS.len();
        *self = Self::load(next);
    }

    pub fn prev_level(&mut self) {
        let prev = (self.level + LEVELS.len() - 1) % LEVELS.len();
        *self = Self::load(prev);
    }
}

/// Швидка самоперевірка рушія при старті на платі.
pub fn selftest() -> (usize, usize) {
    let mut run = 0usize;
    let mut failed = 0usize;
    let mut check = |ok: bool| {
        run += 1;
        if !ok {
            failed += 1;
        }
    };

    // Синтетичний рівень: гравець, ящик і ціль у ряд
    let mut s = Sokoban::parse(&["#####", "#@$.#", "#####"], 0);
    check(s.box_count() == 1 && s.goal_count() == 1);
    check(s.try_move(Dir::Right) == MoveResult::Solved);
    check(s.is_solved());

    // Оригінальний рівень 1: 6 ящиків, 6 цілей, гравець усередині кімнати
    let l1 = Sokoban::load(0);
    check(l1.box_count() == 6 && l1.goal_count() == 6);
    check(l1.inside[l1.player] && !l1.wall[l1.player]);
    check(Sokoban::load(49).box_count() > 0);

    (run, failed)
}

