    use std::collections::{HashMap, VecDeque};

    type Key = (usize, Vec<usize>);

    fn key(s: &Sokoban) -> Key {
        let mut boxes: Vec<usize> = (0..MAX_CELLS).filter(|&i| s.box_at[i]).collect();
        boxes.sort_unstable();
        (s.player, boxes)
    }

    /// Відстані (в кроках, без урахування ящиків) від кожної клітинки до найближчої цілі.
    fn goal_distance(s: &Sokoban) -> [u16; MAX_CELLS] {
        let mut d = [u16::MAX; MAX_CELLS];
        let mut q = VecDeque::new();
        for c in 0..MAX_CELLS {
            if s.goal[c] && s.inside[c] {
                d[c] = 0;
                q.push_back(c);
            }
        }
        while let Some(cur) = q.pop_front() {
            let (cx, cy) = ((cur % MAX_W) as i32, (cur / MAX_W) as i32);
            for (dx, dy) in [(-1i32, 0i32), (1, 0), (0, -1), (0, 1)] {
                if let Some(n) = s.idx(cx + dx, cy + dy)
                    && s.inside[n]
                    && d[n] == u16::MAX
                {
                    d[n] = d[cur].saturating_add(1);
                    q.push_back(n);
                }
            }
        }
        d
    }

    fn heuristic(s: &Sokoban, gd: &[u16; MAX_CELLS]) -> u32 {
        (0..MAX_CELLS)
            .filter(|&i| s.box_at[i])
            .map(|i| {
                if s.goal[i] {
                    0
                } else if gd[i] == u16::MAX {
                    999
                } else {
                    gd[i] as u32
                }
            })
            .sum()
    }

    /// A* (лише для тестів на хості): евристика — сума відстаней ящиків до цілей.
    fn solve(start: &Sokoban, max_states: usize) -> Option<Vec<u8>> {
        use std::cmp::Reverse;
        use std::collections::BinaryHeap;

        let gd = goal_distance(start);
        let start_key = key(start);
        let mut parent: HashMap<Key, (Key, u8)> = HashMap::new();
        let mut best_cost: HashMap<Key, u32> = HashMap::new();
        let mut heap: BinaryHeap<Reverse<(u32, u32, Key)>> = BinaryHeap::new();
        best_cost.insert(start_key.clone(), 0);
        heap.push(Reverse((heuristic(start, &gd), 0, start_key.clone())));
        let mut expanded = 0usize;

        while let Some(Reverse((_f, g, k))) = heap.pop() {
            expanded += 1;
            if expanded > max_states {
                return None;
            }
            if best_cost.get(&k) != Some(&g) {
                continue;
            }
            let mut state = start.clone();
            state.player = k.0;
            for i in 0..MAX_CELLS {
                state.box_at[i] = false;
            }
            for &b in &k.1 {
                state.box_at[b] = true;
            }
            if state.is_solved() {
                let mut path = Vec::new();
                let mut cur = k;
                while let Some((pk, mv)) = parent.get(&cur) {
                    path.push(*mv);
                    cur = pk.clone();
                }
                path.reverse();
                return Some(path);
            }
            for d in [Dir::Up, Dir::Right, Dir::Down, Dir::Left] {
                let mut next = state.clone();
                if next.try_move(d) == MoveResult::Blocked {
                    continue;
                }
                let nk = key(&next);
                let ng = g + 1;
                let better = match best_cost.get(&nk) {
                    Some(&old) => ng < old,
                    None => true,
                };
                if better {
                    best_cost.insert(nk.clone(), ng);
                    parent.insert(nk.clone(), (k.clone(), d as u8));
                    heap.push(Reverse((ng + heuristic(&next, &gd), ng, nk)));
                }
            }
        }
        None
    }

